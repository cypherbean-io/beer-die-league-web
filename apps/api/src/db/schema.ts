// A league's season (SPEC §3.7), moved through draft → active → ended → finalized only by
// domain/seasons.ts. At most one season per league is active. An ended season finalizes once
// none of its games has an open revision, which locks its standings config. Each timestamp is
// set by the transition it names.
export const seasons = pgTable(
  'seasons',
  {
    id: id(),
    leagueId: uuid('league_id')
      .notNull()
      .references(() => leagues.id),
    name: text('name').notNull(),
    status: text('status', { enum: ['draft', 'active', 'ended', 'finalized'] }).notNull(),
    standingsConfig: jsonb('standings_config').$type<StandingsConfig>().notNull(),
    createdAt: ts('created_at').notNull(),
    startedAt: ts('started_at'),
    endedAt: ts('ended_at'),
    finalizedAt: ts('finalized_at'),
  },
  (t) => [
    // The target of games' (season_id, league_id) foreign key, which keeps every game in one
    // of its own league's seasons.
    unique('seasons_id_league_unique').on(t.id, t.leagueId),
    index('seasons_league_id_idx').on(t.leagueId),
    uniqueIndex('seasons_one_active_per_league')
      .on(t.leagueId)
      .where(sql`${t.status} = 'active'`),
    check('seasons_status_valid', sql`${t.status} in ('draft', 'active', 'ended', 'finalized')`),
    check('seasons_started_has_time', sql`(${t.status} <> 'draft') = (${t.startedAt} is not null)`),
    check(
      'seasons_ended_has_time',
      sql`(${t.status} in ('ended', 'finalized')) = (${t.endedAt} is not null)`,
    ),
    check(
      'seasons_finalized_has_time',
      sql`(${t.status} = 'finalized') = (${t.finalizedAt} is not null)`,
    ),
  ],
);

// A team in one season (SPEC §3.7), moved through its statuses only by domain/teams.ts: a
// member proposes it with a partner (proposed), the partner accepts (accepted), and a
// commissioner approves it (approved); until then it can be withdrawn or rejected. The
// proposer and partner are the pair it was proposed with; an approved team's players are its
// roster, which a commissioner can change. `name_key` (NFKC + lowercase, derived by the server)
// keeps the names of a season's live teams unique.
export const seasonTeams = pgTable(
  'season_teams',
  {
    id: id(),
    seasonId: uuid('season_id')
      .notNull()
      .references(() => seasons.id),
    name: text('name').notNull(),
    nameKey: text('name_key').notNull(),
    status: text('status', {
      enum: ['proposed', 'accepted', 'approved', 'rejected', 'withdrawn'],
    }).notNull(),
    proposedBy: uuid('proposed_by')
      .notNull()
      .references(() => memberships.id),
    partnerId: uuid('partner_id')
      .notNull()
      .references(() => memberships.id),
    createdAt: ts('created_at').notNull(),
  },
  (t) => [
    // The target of team_roster's (team_id, season_id) foreign key.
    unique('season_teams_id_season_unique').on(t.id, t.seasonId),
    index('season_teams_season_id_idx').on(t.seasonId),
    uniqueIndex('season_teams_live_name_unique')
      .on(t.seasonId, t.nameKey)
      .where(sql`${t.status} in ('proposed', 'accepted', 'approved')`),
    // Counting a member's proposals in a season.
    index('season_teams_season_proposer_idx').on(t.seasonId, t.proposedBy),
    check(
      'season_teams_status_valid',
      sql`${t.status} in ('proposed', 'accepted', 'approved', 'rejected', 'withdrawn')`,
    ),
    check('season_teams_partner_not_proposer', sql`${t.partnerId} <> ${t.proposedBy}`),
  ],
);

// Who has been on each team, and when. A player's row opens when they commit to the team (the
// proposer on proposing it, the partner on accepting, or a commissioner adds them) and closes
// when they leave it (it is rejected or withdrawn, or a commissioner replaces them). Rows are
// never deleted. The partial unique index allows each player one open row per season, so one
// team per season. A season game stores its own players and teams, so closing a row never
// rewrites one.
export const teamRoster = pgTable(
  'team_roster',
  {
    id: id(),
    teamId: uuid('team_id').notNull(),
    // Always the team's own season (the foreign key below); carried here for the index.
    seasonId: uuid('season_id').notNull(),
    membershipId: uuid('membership_id')
      .notNull()
      .references(() => memberships.id),
    validFrom: ts('valid_from').notNull(),
    validTo: ts('valid_to'),
  },
  (t) => [
    foreignKey({
      name: 'team_roster_team_season_fk',
      columns: [t.teamId, t.seasonId],
      foreignColumns: [seasonTeams.id, seasonTeams.seasonId],
    }),
    index('team_roster_team_id_idx').on(t.teamId),
    uniqueIndex('team_roster_one_team_per_season')
      .on(t.seasonId, t.membershipId)
      .where(sql`${t.validTo} is null`),
    check('team_roster_valid_range', sql`${t.validTo} is null or ${t.validTo} >= ${t.validFrom}`),
  ],
);

// A recorded game. Its rules snapshot is the league rules at first submission, and every
// revision is checked against it, so editing the league rules never re-validates a game.
// Retrying a submission with the same idempotency key returns this game, provided the
// payload hash matches. A season game's teams are on its revisions.
export const games = pgTable(
  'games',
  {
    id: id(),
    leagueId: uuid('league_id')
      .notNull()
      .references(() => leagues.id),
    kind: text('kind', { enum: ['season', 'exhibition'] }).notNull(),
    // Set exactly when the game is a season game.
    seasonId: uuid('season_id'),
    status: text('status', { enum: ['pending', 'confirmed', 'expired', 'voided'] }).notNull(),
    openRevisionId: uuid('open_revision_id').references((): AnyPgColumn => gameRevisions.id),
    // The revision stats read. Set only by settleRevision (domain/games.ts).
    confirmedRevisionId: uuid('confirmed_revision_id').references(
      (): AnyPgColumn => gameRevisions.id,
    ),
    // When the game first counted, also set only by settleRevision. A reopened revision that
    // confirms keeps it, so an exhibition game's correction window never restarts.
    confirmedAt: ts('confirmed_at'),
    // Set at first submission (or when a confirmed game is reopened); corrections keep it.
    windowExpiresAt: ts('window_expires_at'),
    rulesSnapshot: jsonb('rules_snapshot').$type<Rules>().notNull(),
    submittedBy: uuid('submitted_by')
      .notNull()
      .references(() => memberships.id),
    idempotencyKey: uuid('idempotency_key').notNull(),
    payloadSha256: text('payload_sha256').notNull(),
    createdAt: ts('created_at').notNull(),
  },
  (t) => [
    unique('games_idempotency_unique').on(t.leagueId, t.submittedBy, t.idempotencyKey),
    // The target of game_revisions' (game_id, season_id) foreign key.
    unique('games_id_season_unique').on(t.id, t.seasonId),
    foreignKey({
      name: 'games_season_league_fk',
      columns: [t.seasonId, t.leagueId],
      foreignColumns: [seasons.id, seasons.leagueId],
    }),
    // Finalizing a season looks for its games that still have an open revision.
    index('games_season_open_idx')
      .on(t.seasonId)
      .where(sql`${t.openRevisionId} is not null`),
    check('games_kind_valid', sql`${t.kind} in ('season', 'exhibition')`),
    check('games_season_matches_kind', sql`(${t.kind} = 'season') = (${t.seasonId} is not null)`),
    check('games_status_valid', sql`${t.status} in ('pending', 'confirmed', 'expired', 'voided')`),
    // A game that has counted keeps counting through a reopen that expires or is voided.
    check(
      'games_confirmed_has_revision',
      sql`(${t.status} = 'confirmed') = (${t.confirmedRevisionId} is not null)`,
    ),
    check(
      'games_confirmed_has_time',
      sql`(${t.confirmedRevisionId} is not null) = (${t.confirmedAt} is not null)`,
    ),
  ],
);

// Immutable: a correction creates a new revision rather than editing one. A season game's
// revision names the team each side played for, both or neither; a correction keeps them with
// their players, so a later roster change never moves a game to another team. The foreign keys
// keep both teams in the game's own season, so a revision can't name another season's or
// league's team.
export const gameRevisions = pgTable(
  'game_revisions',
  {
    id: id(),
    gameId: uuid('game_id')
      .notNull()
      .references((): AnyPgColumn => games.id),
    number: integer('number').notNull(),
    status: text('status', {
      enum: ['open', 'confirmed', 'superseded', 'expired', 'voided', 'rejected'],
    }).notNull(),
    createdBy: uuid('created_by')
      .notNull()
      .references(() => memberships.id),
    playedAt: ts('played_at').notNull(),
    // The game's season, set exactly when the revision names teams.
    seasonId: uuid('season_id'),
    sideATeamId: uuid('side_a_team_id'),
    sideBTeamId: uuid('side_b_team_id'),
    winner: text('winner', { enum: ['A', 'B'] }).notNull(),
    // checkRules against the game's rules snapshot; empty means the revision conforms.
    ruleViolations: jsonb('rule_violations').$type<RuleViolation[]>().notNull(),
    overrideStatus: text('override_status', { enum: ['requested', 'approved', 'rejected'] }),
    // The commissioner who approved or rejected the review; the decision is also audited.
    overrideBy: uuid('override_by').references(() => memberships.id),
    createdAt: ts('created_at').notNull(),
  },
  (t) => [
    unique('game_revisions_game_number_unique').on(t.gameId, t.number),
    check('game_revisions_number_min', sql`${t.number} >= 1`),
    check(
      'game_revisions_status_valid',
      sql`${t.status} in ('open', 'confirmed', 'superseded', 'expired', 'voided', 'rejected')`,
    ),
    check('game_revisions_winner_valid', sql`${t.winner} in ('A', 'B')`),
    check(
      'game_revisions_override_status_valid',
      sql`${t.overrideStatus} in ('requested', 'approved', 'rejected')`,
    ),
    check(
      'game_revisions_decided_has_override_by',
      sql`coalesce(${t.overrideStatus} in ('approved', 'rejected'), false) = (${t.overrideBy} is not null)`,
    ),
    foreignKey({
      name: 'game_revisions_game_season_fk',
      columns: [t.gameId, t.seasonId],
      foreignColumns: [games.id, games.seasonId],
    }),
    foreignKey({
      name: 'game_revisions_side_a_team_season_fk',
      columns: [t.sideATeamId, t.seasonId],
      foreignColumns: [seasonTeams.id, seasonTeams.seasonId],
    }),
    foreignKey({
      name: 'game_revisions_side_b_team_season_fk',
      columns: [t.sideBTeamId, t.seasonId],
      foreignColumns: [seasonTeams.id, seasonTeams.seasonId],
    }),
    check(
      'game_revisions_teams_both_or_neither',
      sql`(${t.sideATeamId} is null) = (${t.sideBTeamId} is null)`,
    ),
    // With the check above, every column of each foreign key is set or none is, so the keys
    // always apply to a revision that names teams.
    check(
      'game_revisions_teams_have_season',
      sql`(${t.seasonId} is null) = (${t.sideATeamId} is null)`,
    ),
    check('game_revisions_teams_distinct', sql`${t.sideATeamId} <> ${t.sideBTeamId}`),
  ],
);

