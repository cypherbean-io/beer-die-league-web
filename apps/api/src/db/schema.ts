const citext = customType<{ data: string }>({ dataType: () => 'citext' });

// Every timestamp is timestamptz in UTC, and its value always comes from the injected Clock.
const ts = (name: string) => timestamp(name, { withTimezone: true, mode: 'date' });

// UUIDv7, generated by Postgres 18.
const id = () =>
  uuid('id')
    .primaryKey()
    .default(sql`uuidv7()`);

export const users = pgTable('users', {
  id: id(),
  // Null once the account is deleted.
  email: citext('email').unique(),
  createdAt: ts('created_at').notNull(),
  deletedAt: ts('deleted_at'),
});

// One live code per email: requesting a new code overwrites the row, which invalidates the
// earlier code. Only an HMAC of the code is stored.
